package com.fahim.geminiApiComposeStarter.security

import android.content.Context
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKey
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Manages secure AES-256-GCM encryption/decryption of the Gemini API key
 * backed by Android Keystore, and persists ciphertext and IV in EncryptedSharedPreferences.
 */
class SecureApiKeyManager(private val context: Context) {

    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_ALIAS = "GeminiApiKey_AES256_GCM"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_LENGTH = 128
        private const val PREFS_NAME = "secure_api_key_preferences"
        private const val PREF_KEY_CIPHERTEXT = "encrypted_api_key_ciphertext"
        private const val PREF_KEY_IV = "encrypted_api_key_iv"
    }

    private val keyStore: KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply {
        load(null)
    }

    private val securePrefs: SharedPreferences by lazy {
        val masterKey = MasterKey.Builder(context)
            .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
            .build()
        EncryptedSharedPreferences.create(
            context,
            PREFS_NAME,
            masterKey,
            EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
            EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM
        )
    }

    /**
     * Generates or retrieves a 256-bit AES key from the Android Keystore.
     */
    private fun getOrCreateSecretKey(): SecretKey {
        if (!keyStore.containsAlias(KEY_ALIAS)) {
            val keyGenerator = KeyGenerator.getInstance(
                KeyProperties.KEY_ALGORITHM_AES,
                ANDROID_KEYSTORE
            )
            val spec = KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build()

            keyGenerator.init(spec)
            return keyGenerator.generateKey()
        }

        val entry = keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry
            ?: throw IllegalStateException("Key alias $KEY_ALIAS is not a SecretKeyEntry")
        return entry.secretKey
    }

    /**
     * Checks if ciphertext and initialization vector are stored.
     */
    fun hasApiKey(): Boolean {
        return securePrefs.contains(PREF_KEY_CIPHERTEXT) && securePrefs.contains(PREF_KEY_IV)
    }

    /**
     * Encrypts the provided API key with AES-256-GCM using Android Keystore
     * and persists only ciphertext and IV.
     * Prevents unnecessary repeated overwriting when the existing key is identical.
     */
    fun storeApiKey(apiKey: String, forceOverwrite: Boolean = false) {
        if (apiKey.isBlank()) return

        if (!forceOverwrite && hasApiKey()) {
            val currentKey = runCatching { getDecryptedApiKey() }.getOrNull()
            if (currentKey == apiKey) {
                return
            }
        }

        val secretKey = getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)

        val iv = cipher.iv // Fresh random IV generated by Android Keystore
        val ciphertext = cipher.doFinal(apiKey.toByteArray(Charsets.UTF_8))

        val ivBase64 = Base64.encodeToString(iv, Base64.NO_WRAP)
        val ciphertextBase64 = Base64.encodeToString(ciphertext, Base64.NO_WRAP)

        securePrefs.edit()
            .putString(PREF_KEY_IV, ivBase64)
            .putString(PREF_KEY_CIPHERTEXT, ciphertextBase64)
            .apply()
    }

    /**
     * Decrypts and returns the API key into memory.
     * Invoked strictly when constructing GenerativeModel.
     */
    fun getDecryptedApiKey(): String? {
        val ivBase64 = securePrefs.getString(PREF_KEY_IV, null) ?: return null
        val ciphertextBase64 = securePrefs.getString(PREF_KEY_CIPHERTEXT, null) ?: return null

        val iv = Base64.decode(ivBase64, Base64.NO_WRAP)
        val ciphertext = Base64.decode(ciphertextBase64, Base64.NO_WRAP)

        val secretKey = getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        val spec = GCMParameterSpec(GCM_TAG_LENGTH, iv)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, spec)

        val plaintextBytes = cipher.doFinal(ciphertext)
        return String(plaintextBytes, Charsets.UTF_8)
    }

    /**
     * Removes the stored ciphertext and IV.
     */
    fun clear() {
        securePrefs.edit()
            .remove(PREF_KEY_CIPHERTEXT)
            .remove(PREF_KEY_IV)
            .apply()
    }
}
